#!/usr/bin/env node
'use strict';

// Generates the compact wiki entry points from immutable reasoning-trace
// frontmatter. The installed Tier 1 payload never receives this authoring-time
// script; its output is ordinary Markdown.
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const TRACE_DIR = path.join('wiki', 'reasoning');
const OUTPUTS = {
  status: path.join('wiki', 'status.md'),
  index: path.join('wiki', 'index', 'reasoning.md'),
};

function list(value) {
  return (value || '').split(',').map((item) => item.trim()).filter(Boolean);
}

function parseTrace(file, body) {
  const match = body.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/);
  const fields = {};
  if (match) {
    for (const line of match[1].split(/\r?\n/)) {
      const separator = line.indexOf(':');
      if (separator === -1) throw new Error(`${file} has malformed frontmatter: ${line}`);
      fields[line.slice(0, separator).trim()] = line.slice(separator + 1).trim();
    }
  }
  // Older immutable traces predate the common frontmatter contract. They remain
  // indexable from their dated filename; all newly filed traces carry the full
  // fields described in wiki/reasoning/README.md.
  const datedName = path.basename(file).match(/^(\d{4}-\d{2}-\d{2})-/);
  if (!fields.date && !datedName) throw new Error(`${file} is missing a date and dated filename`);
  return {
    file,
    date: fields.date || datedName[1],
    source: fields.source || 'historical',
    topics: list(fields.topics),
    decisions: list(fields.decisions),
    status: fields.status || 'historical',
    supersedes: fields.supersedes || '',
    tags: list(fields.tags),
    summary: fields.summary || '',
  };
}

function traces(root = ROOT) {
  const directory = path.join(root, TRACE_DIR);
  return fs.readdirSync(directory)
    .filter((file) => file.endsWith('.md') && file !== 'README.md')
    .sort()
    .map((file) => parseTrace(
      path.join('reasoning', file),
      fs.readFileSync(path.join(directory, file), 'utf8'),
    ))
    .sort((left, right) => `${right.date}/${right.file}`.localeCompare(`${left.date}/${left.file}`));
}

// The two generated pages sit at different depths: wiki/status.md is one level
// above wiki/reasoning/, while wiki/index/reasoning.md is a sibling directory.
// Each caller passes the prefix correct for its own output path.
function link(trace, prefix) {
  return `[${path.basename(trace.file, '.md')}](${trace.file.replace(/^reasoning\//, prefix)})`;
}

function renderStatus(records) {
  const current = records.filter((trace) => trace.status === 'current');
  const lines = [
    '# Current state',
    '',
    '<!-- Generated by scripts/build-wiki-index.js; do not edit by hand. -->',
    '',
    'This page is generated from current reasoning traces. Read the linked trace for detail, then [Tickets](Tickets.md) for the live work board.',
    '',
    '## Current',
    '',
  ];
  if (!current.length) lines.push('No current trace is marked in `wiki/reasoning/`.');
  for (const trace of current) {
    const detail = trace.summary || `Current trace from ${trace.source}.`;
    lines.push(`- **${trace.date} — ${link(trace, 'reasoning/')}**: ${detail}`);
  }
  return `${lines.join('\n')}\n`;
}

function display(values) {
  return values.length ? values.join(', ') : '—';
}

function renderIndex(records) {
  const lines = [
    '# Reasoning trace index',
    '',
    '<!-- Generated by scripts/build-wiki-index.js; do not edit by hand. -->',
    '',
    'Every immutable reasoning trace, newest first. `current` entries feed the current-state page; `superseded` entries remain reachable with their successor target.',
    '',
    '| Date | State | Trace | Topics | Decisions | Tags |',
    '| --- | --- | --- | --- | --- | --- |',
  ];
  for (const trace of records) {
    const state = trace.supersedes ? `${trace.status} → ${trace.supersedes}` : trace.status;
    lines.push(`| ${trace.date} | ${state} | ${link(trace, '../reasoning/')} | ${display(trace.topics)} | ${display(trace.decisions)} | ${display(trace.tags)} |`);
  }
  return `${lines.join('\n')}\n`;
}

function render(root = ROOT) {
  const records = traces(root);
  return {
    [OUTPUTS.status]: renderStatus(records),
    [OUTPUTS.index]: renderIndex(records),
  };
}

function write(root = ROOT) {
  for (const [relative, body] of Object.entries(render(root))) {
    fs.writeFileSync(path.join(root, relative), body);
  }
}

if (require.main === module) write();

module.exports = { OUTPUTS, parseTrace, render, renderIndex, renderStatus, traces, write };
